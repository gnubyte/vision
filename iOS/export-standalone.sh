#!/bin/bash
# Write the iPhone app out as a repository of its own.
#
#   ./export-standalone.sh <folder>
#
# In this repository the app builds the harness's shared code straight from ../Sources/VisionHarnessCore. A
# repository that holds only the app needs its own copy of those files: this writes the app, a copy of exactly the
# shared files it builds (under Core/), a project.yml that points at them, the IPA workflow, and a README — a
# tree that builds on its own with `./build-ipa.sh`. Run it again to refresh the copy after the harness changes.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$ROOT/.." && pwd)"
DEST="${1:?usage: export-standalone.sh <folder>}"
mkdir -p "$DEST"
DEST="$(cd "$DEST" && pwd)"
[ "$DEST" != "$ROOT" ] && [ "$DEST" != "$REPO" ] || { echo "choose a folder outside this repository's own files" >&2; exit 1; }

echo "==> writing the app to $DEST"
mkdir -p "$DEST/Core" "$DEST/.github/workflows"
for item in Vision VisionTests tools; do
  mkdir -p "$DEST/$item"
  cp -R "$ROOT/$item/." "$DEST/$item/"
done
rm -f "$DEST/Vision/Info.plist"
cp "$ROOT/build-ipa.sh" "$ROOT/simulator-smoke.sh" "$ROOT/live-check.sh" "$DEST/"

# The shared files, exactly the ones project.yml lists.
count=0
while IFS= read -r relative; do
  cp "$ROOT/$relative" "$DEST/Core/$(basename "$relative")"
  count=$((count + 1))
done < <(sed -n 's|^ *- path: \(\.\./Sources/VisionHarnessCore/.*\.swift\)$|\1|p' "$ROOT/project.yml")
[ "$count" -gt 0 ] || { echo "found no shared files in project.yml" >&2; exit 1; }
echo "    $count shared harness files → Core/"

# project.yml, pointing at the copy.
python3 - "$ROOT/project.yml" "$DEST/project.yml" <<'PY'
import re, sys
text = open(sys.argv[1]).read()
text = re.sub(r"\.\./Sources/VisionHarnessCore/(?:[A-Za-z]+/)?([A-Za-z0-9_+]+\.swift)", r"Core/\1", text)
head = """# The Xcode project for Vision on iPhone and iPad, generated with XcodeGen (brew install xcodegen):
#
#   xcodegen && open Vision.xcodeproj
#
# Core/ holds the harness code the app shares with Vision for macOS (the Spark Swapper client, the
# OpenAI-compatible client, certificate pinning, picture roll-off, attachment handling, prompt history). It is a
# copy made by the harness repository's iOS/export-standalone.sh: change those files there, not here.
"""
body = text[text.index("name: Vision"):]
open(sys.argv[2], "w").write(head + body)
PY

cat > "$DEST/.gitignore" <<'IGNORE'
# Generated by XcodeGen from project.yml
Vision.xcodeproj/
Vision/Info.plist
# Build output
build/
DerivedData/
xcuserdata/
.DS_Store
IGNORE

cat > "$DEST/.github/workflows/ios.yml" <<'WORKFLOW'
name: iOS IPA

# Build Vision for iPhone on every push and pull request, keep the IPA as an artifact (Actions ▸ the run ▸
# Artifacts ▸ Vision-iOS-ipa), open every screen in the simulator on demo data, and check the app's code against a
# real Spark Swapper in demo mode. A version tag (v*) also publishes the IPA as a GitHub release.
# The IPA is unsigned: install it with a sideloading tool that signs with your own Apple ID, or run the Xcode
# project on your phone.

on:
  push:
    branches: ['**']
    tags: ['v*']
  pull_request:
  workflow_dispatch:

permissions:
  contents: write

concurrency:
  group: ios-${{ github.ref }}
  cancel-in-progress: true

jobs:
  ipa:
    runs-on: macos-15
    timeout-minutes: 40
    steps:
      - name: Check out source
        uses: actions/checkout@v4

      - name: Toolchain
        run: |
          xcodebuild -version
          command -v xcodegen >/dev/null || brew install xcodegen
          xcodegen --version

      - name: Build the IPA
        run: bash build-ipa.sh

      - name: Keep the IPA as an artifact
        uses: actions/upload-artifact@v4
        with:
          name: Vision-iOS-ipa
          path: build/Vision.ipa
          if-no-files-found: error

      - name: Run it in the simulator (demo data, every screen)
        run: bash simulator-smoke.sh

      - name: Live check against Spark Swapper
        run: bash live-check.sh

      - name: Keep the screenshots
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: Vision-iOS-screens
          path: build/screens/*.png
          if-no-files-found: ignore

      - name: Publish the release
        if: startsWith(github.ref, 'refs/tags/v')
        env:
          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        run: |
          TAG="${GITHUB_REF#refs/tags/}"
          gh release delete "$TAG" --yes 2>/dev/null || true
          gh release create "$TAG" --title "Vision for iPhone $TAG" --generate-notes build/Vision.ipa
WORKFLOW

cat > "$DEST/README.md" <<'README'
# Vision for iPhone

Chat with the model your own [Spark Swapper](https://github.com/gnubyte/DGX-Spark-Swapper) box serves — a DGX
Spark or a Strix Halo — and switch what it serves, from an iPhone or iPad (iOS 17+). The companion of Vision
for macOS; `Core/` is the same harness code the Mac app runs.

- **Boxes** — add a box by pasting the connection code from the Swapper's **Connect** tab (it carries the
  address, the certificate and an app token, so no password is stored), or with the address and the web page's
  login (the certificate's fingerprint is shown for you to approve first; on Swapper 2.0+ the login is traded
  for an app token). Each box shows what it serves, its context window, speed and memory; tap a model to
  switch and watch the switch step by step.
- **Chats** — streamed replies rendered as Markdown. Attach photos, paste a picture, or add files and PDFs. A
  chat stays inside the model's picture limit: the newest pictures travel, older ones roll off (and stay in the
  chat), and a server that takes fewer says so once and the app remembers it. PDFs go as their text; scanned
  ones as pictures of their pages.
- **Prompt history** — per chat or across all chats: sort by time or duration, search, copy or share as
  Markdown, CSV or JSON, and reopen the photos and files a prompt carried.

## Get it on your phone

**From Xcode** (the simplest way to get it signed):

```bash
brew install xcodegen
xcodegen
open Vision.xcodeproj
```

Select the **Vision** target ▸ **Signing & Capabilities**, choose your team (a free Apple ID works), change
the bundle identifier if Xcode says it is taken, plug in the phone and press Run. With a free Apple ID the app
has to be re-installed every seven days; the first launch needs **Settings ▸ General ▸ VPN & Device
Management ▸ trust your developer certificate** on the phone.

**From the IPA.** Every push builds `Vision.ipa` (Actions ▸ the latest **iOS IPA** run ▸ Artifacts ▸
`Vision-iOS-ipa`; a `v*` tag publishes it as a release), or build it yourself:

```bash
./build-ipa.sh        # → build/Vision.ipa
```

The IPA is **unsigned** and iOS installs only signed apps: open it with AltStore or Sideloadly, which sign it
with your Apple ID and install it.

The phone has to reach the box: the same network, or a VPN such as Tailscale.

## Checking it

```bash
./simulator-smoke.sh   # every screen in the simulator on built-in demo data; screenshots in build/screens
./live-check.sh        # the app's code against the real Spark Swapper (demo mode) and a picture-limited model server
```

`-VisionDemo YES` on the app's command line opens it on a made-up box and chat: no network, nothing kept.

## Layout

```
Vision/          the app: SwiftUI screens and its model (MobileModel.swift)
VisionTests/     the live check's tests
Core/            harness code shared with Vision for macOS — a copy; change it in the harness repository
tools/           the stand-in model server the live check uses
project.yml      the XcodeGen project
```
README
chmod +x "$DEST/build-ipa.sh" "$DEST/simulator-smoke.sh" "$DEST/live-check.sh"
echo "==> done. To publish it: cd \"$DEST\" && git init -b main && git add -A && git commit -m 'Vision for iPhone' && git remote add origin <your repo> && git push -u origin main"
